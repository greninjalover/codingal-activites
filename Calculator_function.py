def add(n1, n2):
    return n1+n2

def sub(n1, n2):
    return n1-n2

def div(n1, n2):
    return n1/n2

def mult(n1, n2):
    return n1*n2



n1= int(input("Enter The First Number"))
n2= int(input("Enter The Second Number"))



print(add(n1, n2))
print(sub(n1, n2))
print(div(n1, n2))
print(mult(n1, n2))
